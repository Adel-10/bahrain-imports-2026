"""Helpers for writing the markdown reports.

Every report in reports/ is generated by a script, so its numbers always match the data
and the analysis code. The scripts build the text with Python f-strings; this module holds
the small pieces they share:

* **Number formatting** in one consistent style: signed percentages ("-54%"), BD millions
  ("624"), "% of normal" ("46%"), and phrases such as "about two-thirds".
* **Markdown tables** from pandas DataFrames.
* **Paragraph joining.** In the source code the report text is wrapped to a readable line
  length. Some markdown viewers show those line breaks literally, which breaks sentences in
  the middle, so ``write_markdown`` joins the lines of each paragraph and list item before the
  file is saved. Tables, headings, images and code blocks are left exactly as written.
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# Numbers as text
# ---------------------------------------------------------------------------
def pct(x: float, dp: int = 0) -> str:
    """Signed percentage: -53.6 -> '-54%', 7.9 -> '+8%', 0.2 -> '0%'."""
    r = round(x, dp)
    return "0%" if r == 0 else f"{r:+.{dp}f}%"


def signed(x: float, dp: int = 0) -> str:
    """Signed number without a % sign: 3.2 -> '+3', -0.4 -> '0'."""
    r = round(x, dp)
    return "0" if r == 0 else f"{r:+.{dp}f}"


def bd_m(x: float) -> str:
    """A value in BD as whole millions: 624_400_000 -> '624'."""
    return f"{x / 1e6:,.0f}"


def pon(x: float) -> str:
    """'% of normal': 46.2 -> '46%'; missing values become a dash."""
    return "-" if pd.isna(x) else f"{x:.0f}%"


def share_words(p: float) -> str:
    """A percentage close to a simple fraction as words: 66.4 -> 'two-thirds'; otherwise '58%'."""
    for value, words in ((25, "a quarter"), (100 / 3, "a third"), (50, "half"), (200 / 3, "two-thirds"),
                         (75, "three-quarters")):
        if abs(p - value) <= 3:
            return words
    return f"{p:.0f}%"


def times(x: float) -> str:
    """A '% of normal' above 150 as a multiple: 292 -> 'about 3 times'; smaller values stay as '% of'."""
    return f"about {x / 100:.0f} times" if x >= 150 else f"{x:.0f}% of"


def and_list(items) -> str:
    """['a', 'b', 'c'] -> 'a, b and c'."""
    items = list(items)
    if not items:
        return ""
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def short_period(label: str) -> str:
    """'Since the war (Mar-Jul)' -> 'Mar-Jul'; other labels are returned unchanged."""
    return label.split("(")[1].rstrip(")") if label.startswith("Since") else label


def region_text(label: str) -> str:
    """Region names as they read inside a sentence."""
    return {"Other Middle East": "the rest of the Middle East", "Americas": "the Americas"}.get(label, label)


# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------
def md_table(df: pd.DataFrame, floatfmt: str = ".2f") -> str:
    """A DataFrame as a markdown table. Floats use `floatfmt`; integers get thousands separators."""
    def fmt(x):
        if isinstance(x, float):
            return format(x, floatfmt)
        if isinstance(x, (int, np.integer)):
            return f"{x:,}"
        return str(x)
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *body])


# A line starts a new markdown block (rather than continuing the previous paragraph) if it is a
# heading, table row, image, quote, code fence, horizontal rule or list item. Numbered list items
# are limited to 1-2 digits so that a wrapped line starting with a year ("2026. The ...") is joined.
_BLOCK_START = re.compile(r"^\s*(#|\||!\[|>|```|---|[*-]\s|\d{1,2}\.\s)")
_NOT_JOINABLE = ("#", "|", "![", "```", "---", ">")


def join_paragraphs(text: str) -> str:
    """Join the wrapped lines of each paragraph or list item into one line.

    A line is appended to the previous one when it is not blank, does not start a new block,
    and the previous line is ordinary text (not a heading, table row, image, quote or rule).
    Indented lines under a list item are joined to that item. Code blocks are left alone.
    """
    out: list[str] = []
    in_code = False
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("```"):
            in_code = not in_code
            out.append(line)
            continue
        if in_code:
            out.append(line)
            continue
        previous_is_text = bool(out) and bool(out[-1].strip()) and not out[-1].lstrip().startswith(_NOT_JOINABLE)
        if previous_is_text and stripped and not _BLOCK_START.match(line):
            out[-1] = out[-1].rstrip() + " " + stripped
        else:
            out.append(line)
    return "\n".join(out)


def write_markdown(path: Path, text: str) -> None:
    """Save a report: paragraphs joined, runs of blank lines collapsed, one newline at the end."""
    text = join_paragraphs(text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def footer(script: str, extra: str = "") -> str:
    """The note at the end of each report saying which script wrote it."""
    note = f"*This report is generated by `{script}`{extra}. Re-running the pipeline (`python src/run_all.py`) " \
           f"refreshes every number and chart. Data: Bahrain Open Data Portal (iGA), www.data.gov.bh.*"
    return "---\n\n" + note
